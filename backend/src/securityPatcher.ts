import { safeFire, fireAndForget } from './utils/safeFire';
import { execAsync } from './utils/execAsync';
import path from 'path';
import os from 'os';
import fs from 'fs';
import axios from 'axios';
import simpleGit from 'simple-git';
import logger from './logger';
import { sendTelegramMessage } from './telegramClient';

const SENSITIVE_PATHS: string[] = [
  'auth','middleware','stripe','paypal','payout',
  'billing','users','firebaseAdmin','jwt','token',
];

interface SecurityIssue {
  auto_fixable: boolean;
  issue_type: string;
  severity: string;
  title: string;
  description: string;
  [key: string]: any;
}

interface PRParams {
  repoFullName: string;
  branchName: string;
  title: string;
  body: string;
}

// Direct GitHub API call — prCreator.js has a debug-fix-specific signature
async function openSecurityPR({ repoFullName, branchName, title, body }: PRParams): Promise<string | null> {
  try {
    const res = await axios.post(
      `https://api.github.com/repos/${repoFullName}/pulls`,
      { title, body, head: branchName, base: 'main' },
      {
        headers: {
          Authorization: `Bearer ${process.env['GITHUB_TOKEN']}`,
          Accept:        'application/vnd.github+json',
        },
      }
    );
    return res.data.html_url;
  } catch (err: any) {
    logger.error({ err: err.stack ?? err.message, repoFullName }, 'Security PR creation failed');
    return null;
  }
}

async function applySecurityPatches(repoFullName: string, repoName: string, issues: SecurityIssue[], topicId?: any) {
  const autoFixable = issues.filter(i =>
    i.auto_fixable &&
    i.issue_type === 'vulnerability' &&
    i.severity !== 'critical' &&
    !SENSITIVE_PATHS.some(p => (i.description || '').toLowerCase().includes(p))
  );

  if (autoFixable.length === 0) {
    logger.info({ repoFullName }, 'No auto-fixable issues');
    return;
  }

  let tmpDir: string | null = null;

  try {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'sentinel-patch-'));
    const git = simpleGit();
    await git.clone(
      `https://${process.env['GITHUB_TOKEN']}@github.com/${repoFullName}.git`, tmpDir
    );

    const cloneGit   = simpleGit(tmpDir);
    await cloneGit.addConfig('user.email', 'sentinel@project-sentinel.app');
    await cloneGit.addConfig('user.name',  'Project Sentinel');
    const branchName = `sentinel/security-patch-${Date.now()}`;
    await cloneGit.checkoutLocalBranch(branchName);

    await execAsync('npm audit fix', { cwd: tmpDir, timeout: 120000, scoped: true });

    const status = await cloneGit.status();
    if (status.files.length === 0) {
      logger.info({ repoFullName }, 'npm audit fix made no changes');
      return;
    }

    await cloneGit.add('package*.json');
    await cloneGit.commit(
      `[sentinel] security: npm audit fix (${autoFixable.length} vulnerabilities)\n\n` +
      autoFixable.map(i => `- ${i.title}`).join('\n')
    );
    await cloneGit.push([
      `https://${process.env['GITHUB_TOKEN']}@github.com/${repoFullName}.git`,
      branchName,
    ]);

    const prUrl = await openSecurityPR({
      repoFullName, branchName,
      title: `[Sentinel Security] Fix ${autoFixable.length} npm vulnerabilities`,
      body: [
        '## Sentinel Security Patch',
        '',
        'Auto-generated by Project Sentinel Phase 9.',
        '',
        '### Fixed',
        autoFixable.map(i => `- **${i.severity}**: ${i.title}`).join('\n'),
        '',
        '### Safety',
        'Only `package.json` and `package-lock.json` modified.',
        'No auth, payment, or identity files touched.',
        'Applied via `npm audit fix` (no --force).',
      ].join('\n'),
    });

    await safeFire(sendTelegramMessage([
      `🔒 Security Patch PR — ${repoName}`,
      ``,
      `${autoFixable.length} vulnerabilities patched.`,
      `Only package.json updated — no app code touched.`,
      ``,
      prUrl || 'PR created on GitHub',
    ].join('\n'), null, topicId), { label: 'securityPatcher' })

    logger.info({ repoFullName, branchName, prUrl }, 'Security patch PR created');

  } catch (err: any) {
    logger.error({ err: err.stack ?? err.message, repoFullName }, 'Security patch failed');
  } finally {
    if (tmpDir) {
      try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch {}
    }
  }
}

export = { applySecurityPatches };

